"""
library.py
----------
Per-device song history — the "your songs" list — in Postgres (Neon).

Chordex has no accounts. The browser generates a random device id (see
``lib/device.ts``) and sends it with each request; history is scoped to that id,
so one visitor can never read another's songs.

The store is entirely optional. With no ``DATABASE_URL`` every function is a
no-op, which keeps local development, the test suite and CI free of a database
dependency. Nothing here can break an analysis either: every call is
best-effort and logs instead of raising.

Public API:
    enabled() -> bool
    valid_device_id(device_id) -> bool
    init() -> None
    save(job_id, device_id, result) -> bool
    list_songs(device_id, limit) -> list[dict]
    get_song(job_id, device_id) -> dict | None
    delete_song(job_id, device_id) -> bool
"""

from __future__ import annotations

import json
import logging
import os
import re
from typing import Any

logger = logging.getLogger(__name__)

#: Device ids are generated by the browser (crypto.randomUUID or a fallback)
#: and echoed back on every request, so validate before it reaches SQL.
_DEVICE_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")

_SCHEMA = (
    """
    CREATE TABLE IF NOT EXISTS chordex_songs (
        id              TEXT PRIMARY KEY,
        device_id       TEXT NOT NULL,
        created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
        source_name     TEXT,
        artist          TEXT,
        lyrics_language TEXT,
        duration        DOUBLE PRECISION,
        song_key        TEXT,
        tempo           DOUBLE PRECISION,
        engine          TEXT,
        lyrics_status   TEXT,
        lyrics_source   TEXT,
        n_chords        INTEGER NOT NULL DEFAULT 0,
        has_lyrics      BOOLEAN NOT NULL DEFAULT false,
        payload         JSONB NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS chordex_songs_device_created_idx
        ON chordex_songs (device_id, created_at DESC)
    """,
)

_META_COLUMNS = """
    id, created_at, source_name, artist, lyrics_language, duration,
    song_key, tempo, engine, lyrics_status, lyrics_source, n_chords, has_lyrics
"""

# The payload is the whole AnalysisResult, so a saved song renders exactly like
# a live one (minus the audio, which is deleted two hours after analysis).
# device_id is deliberately absent from the UPDATE and the WHERE guards the
# owner: a second device can never take over an existing row.
_SAVE_SQL = f"""
    INSERT INTO chordex_songs (
        id, device_id, source_name, artist, lyrics_language, duration,
        song_key, tempo, engine, lyrics_status, lyrics_source,
        n_chords, has_lyrics, payload
    ) VALUES (
        %(id)s, %(device_id)s, %(source_name)s, %(artist)s, %(lyrics_language)s,
        %(duration)s, %(song_key)s, %(tempo)s, %(engine)s, %(lyrics_status)s,
        %(lyrics_source)s, %(n_chords)s, %(has_lyrics)s, %(payload)s
    )
    ON CONFLICT (id) DO UPDATE SET
        source_name     = EXCLUDED.source_name,
        artist          = EXCLUDED.artist,
        lyrics_language = EXCLUDED.lyrics_language,
        duration        = EXCLUDED.duration,
        song_key        = EXCLUDED.song_key,
        tempo           = EXCLUDED.tempo,
        engine          = EXCLUDED.engine,
        lyrics_status   = EXCLUDED.lyrics_status,
        lyrics_source   = EXCLUDED.lyrics_source,
        n_chords        = EXCLUDED.n_chords,
        has_lyrics      = EXCLUDED.has_lyrics,
        payload         = EXCLUDED.payload,
        updated_at      = now()
    WHERE chordex_songs.device_id = EXCLUDED.device_id
"""

_LIST_SQL = f"""
    SELECT {_META_COLUMNS}
    FROM chordex_songs
    WHERE device_id = %s
    ORDER BY created_at DESC
    LIMIT %s
"""

_GET_SQL = f"""
    SELECT {_META_COLUMNS}, payload
    FROM chordex_songs
    WHERE id = %s AND device_id = %s
"""

_DELETE_SQL = "DELETE FROM chordex_songs WHERE id = %s AND device_id = %s"

#: Created lazily; tests replace this with a fake pool.
_pool: Any | None = None


# ── config / plumbing ─────────────────────────────────────────────────────

def enabled() -> bool:
    """True when a database is configured (``DATABASE_URL``)."""
    return bool(os.getenv("DATABASE_URL", "").strip())


def valid_device_id(device_id: str | None) -> bool:
    return bool(device_id) and bool(_DEVICE_RE.match(str(device_id)))


def _get_pool():
    """Lazily build the connection pool. Returns None when unconfigured."""
    global _pool
    if _pool is not None:
        return _pool
    dsn = os.getenv("DATABASE_URL", "").strip()
    if not dsn:
        return None
    from psycopg_pool import ConnectionPool

    _pool = ConnectionPool(
        dsn,
        min_size=0,          # nothing held open, so Neon's compute can suspend
        max_size=int(os.getenv("LIBRARY_DB_POOL_MAX", "2")),
        max_idle=60.0,
        timeout=5.0,
        kwargs={
            # Neon's pooled endpoint is PgBouncer in transaction mode, which
            # cannot carry server-side prepared statements between statements.
            "prepare_threshold": None,
        },
    )
    return _pool


def _cursor(conn):
    from psycopg.rows import dict_row

    return conn.cursor(row_factory=dict_row)


def _text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _meta(row: dict) -> dict:
    """A row as the JSON the API returns (``key`` rather than ``song_key``)."""
    created = row.get("created_at")
    return {
        "id": row.get("id"),
        "created_at": created.isoformat() if hasattr(created, "isoformat") else created,
        "source_name": row.get("source_name"),
        "artist": row.get("artist"),
        "key": row.get("song_key"),
        "tempo": row.get("tempo"),
        "duration": row.get("duration"),
        "engine": row.get("engine"),
        "lyrics_language": row.get("lyrics_language"),
        "lyrics_status": row.get("lyrics_status"),
        "lyrics_source": row.get("lyrics_source"),
        "n_chords": row.get("n_chords") or 0,
        "has_lyrics": bool(row.get("has_lyrics")),
    }


# ── public API ────────────────────────────────────────────────────────────

def init() -> None:
    """Create the table and index if they are missing. Never raises."""
    if not enabled():
        return
    try:
        pool = _get_pool()
        with pool.connection() as conn, _cursor(conn) as cur:
            for statement in _SCHEMA:
                cur.execute(statement)
    except Exception as exc:  # a broken store must not stop the app booting
        logger.warning("library: schema init failed (%s)", exc)


def save(job_id: str, device_id: str, result: dict) -> bool:
    """Insert or refresh one song. Returns True when it was written."""
    if not enabled() or not valid_device_id(device_id):
        return False
    try:
        payload = json.dumps(result, ensure_ascii=False)
    except (TypeError, ValueError) as exc:
        logger.warning("library: job %s result is not JSON (%s)", job_id, exc)
        return False

    params = {
        "id": job_id,
        "device_id": device_id,
        "source_name": _text(result.get("source_name")),
        "artist": _text(result.get("artist")),
        "lyrics_language": _text(result.get("lyrics_language")),
        "duration": result.get("duration"),
        "song_key": _text(result.get("key")),
        "tempo": result.get("tempo"),
        "engine": _text(result.get("engine")),
        "lyrics_status": _text(result.get("lyrics_status")),
        "lyrics_source": _text(result.get("lyrics_source")),
        "n_chords": len(result.get("chords") or []),
        "has_lyrics": bool(result.get("lyrics") or result.get("lyric_lines")),
        "payload": payload,
    }
    try:
        with _get_pool().connection() as conn, _cursor(conn) as cur:
            cur.execute(_SAVE_SQL, params)
    except Exception as exc:
        logger.warning("library: save %s failed (%s)", job_id, exc)
        return False
    return True


def list_songs(device_id: str, limit: int = 50) -> list[dict]:
    """Newest first. Empty when unconfigured, unowned or unavailable."""
    if not enabled() or not valid_device_id(device_id):
        return []
    limit = max(1, min(int(limit), 200))
    try:
        with _get_pool().connection() as conn, _cursor(conn) as cur:
            cur.execute(_LIST_SQL, (device_id, limit))
            rows = cur.fetchall()
    except Exception as exc:
        logger.warning("library: list failed (%s)", exc)
        return []
    return [_meta(row) for row in rows]


def get_song(job_id: str, device_id: str) -> dict | None:
    """One saved song including its full ``payload``, or None."""
    if not enabled() or not valid_device_id(device_id):
        return None
    try:
        with _get_pool().connection() as conn, _cursor(conn) as cur:
            cur.execute(_GET_SQL, (job_id, device_id))
            row = cur.fetchone()
    except Exception as exc:
        logger.warning("library: get %s failed (%s)", job_id, exc)
        return None
    if row is None:
        return None
    song = _meta(row)
    song["payload"] = row.get("payload")
    return song


def delete_song(job_id: str, device_id: str) -> bool:
    """Remove one song. Returns True when a row was actually deleted."""
    if not enabled() or not valid_device_id(device_id):
        return False
    try:
        with _get_pool().connection() as conn, _cursor(conn) as cur:
            cur.execute(_DELETE_SQL, (job_id, device_id))
            deleted = cur.rowcount > 0
    except Exception as exc:
        logger.warning("library: delete %s failed (%s)", job_id, exc)
        return False
    return deleted
